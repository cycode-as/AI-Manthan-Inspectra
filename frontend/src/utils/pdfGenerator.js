import { formatDate, formatAnomalyScore, formatProcessingTime, formatCategory } from './formatters';

/**
 * Generate and download a PDF report for an inspection
 * Uses html2pdf.js library for PDF generation
 */
export async function generatePDFReport(inspection, reportElement) {
  // Dynamically import html2pdf library
  const html2pdf = await import('html2pdf.js');
  
  if (!reportElement) {
    throw new Error('Report element not found');
  }

  const filename = `Inspectra_Report_${inspection.inspection_id || inspection.id}_${Date.now()}.pdf`;

  const options = {
    margin: [10, 10, 10, 10],
    filename,
    image: { type: 'jpeg', quality: 0.95 },
    html2canvas: { 
      scale: 2,
      useCORS: true,
      logging: false
    },
    jsPDF: { 
      unit: 'mm', 
      format: 'a4', 
      orientation: 'portrait' 
    },
    pagebreak: { mode: ['avoid-all', 'css', 'legacy'] }
  };

  try {
    // Clone the element to avoid modifying the original
    const clone = reportElement.cloneNode(true);
    
    // Remove no-print elements from clone
    const noPrintElements = clone.querySelectorAll('.no-print');
    noPrintElements.forEach(el => el.remove());

    // Generate PDF
    await html2pdf.default().set(options).from(clone).save();
    
    return { success: true, filename };
  } catch (error) {
    console.error('PDF generation error:', error);
    throw error;
  }
}

/**
 * Alternative: Generate PDF using browser print dialog
 * Falls back to this if html2pdf is not available
 */
export function printReport() {
  window.print();
}

/**
 * Generate a text-based report summary
 * Used as fallback or for data export
 */
export function generateTextReport(inspection) {
  const lines = [
    'INSPECTRA 2.0 - INSPECTION REPORT',
    '=' + '='.repeat(50),
    '',
    `Inspection ID: ${inspection.inspection_id || inspection.id}`,
    `Filename: ${inspection.filename || 'N/A'}`,
    `Category: ${formatCategory(inspection.category)}`,
    `Prediction: ${inspection.prediction || 'N/A'}`,
    `Anomaly Score: ${formatAnomalyScore(inspection.anomaly_score || inspection.anomalyScore)}`,
    `Decision: ${inspection.decision || inspection.status}`,
    `Inference Time: ${formatProcessingTime(inspection.inference_time_ms || inspection.processingTime)}`,
    `Model Version: ${inspection.model_version || inspection.modelVersion || 'N/A'}`,
    `Date: ${formatDate(inspection.created_at || inspection.timestamp)}`,
    '',
    '=' + '='.repeat(50),
    'Generated by Inspectra 2.0 AI Inspection System'
  ];

  return lines.join('\n');
}

/**
 * Download text report
 */
export function downloadTextReport(inspection) {
  const content = generateTextReport(inspection);
  const filename = `Inspectra_Report_${inspection.inspection_id || inspection.id}.txt`;
  
  const blob = new Blob([content], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  
  URL.revokeObjectURL(url);
}
